"""
skill_validator/skill_signer.py — Phidipus v1.0
ed25519 signing and verification for validated skill files.

Architecture contract (R-09 / R-08 / R-17):
  "SkillLoader MUST verify ed25519 signature (.sig file) before loading any
   skill.  Unsigned skills are rejected with an ERROR log entry."

  "All generated skill code MUST pass skill_validator Gates 1, 2, and 3
   before registration.  No exceptions."

  "R-17 (Phase 1 component): every validated skill .py file MUST be signed
   with ed25519 before registration.  This module fulfils the skill-file
   signing half of R-17.  The second half — signing skill_versions.json
   entries — is implemented in evolution/skill_evolver.py (Phase 4)."

This module is the signing half of the skill integrity pipeline.  It is
called by skill_validator/schema_gate.py immediately after a skill passes
all three gates.  The produced .sig file is the cryptographic proof that
the skill has been validated — SkillLoader refuses to load any .py file
that lacks a valid .sig (R-09).

Signing convention
------------------
For every validated skill file ``<name>.py``, this module writes a sibling
signature file ``<name>.sig`` containing the raw 64-byte ed25519 signature
over the UTF-8 bytes of the .py file.

    skill.py   ← skill source code (written by skill_generator)
    skill.sig  ← 64-byte ed25519 signature (written by this module, mode 0600)

The signature covers the **exact bytes on disk** at the moment of signing.
If the .py file is modified after signing, the .sig becomes invalid and
SkillLoader will reject the skill with a SecurityError.

Key files
---------
Private key (signing):  cfg.skill_validator.signing_private_key_file
                        32-byte raw ed25519 private key, mode 0600
                        Generated by installer via hash_utils.generate_installation_keys()

Public key (verifying): cfg.skill_validator.signing_public_key_file
                        32-byte raw ed25519 public key, mode 0644
                        Consumed by skills/skill_loader.py (R-09)

Process: orchestrator (L1)

Security invariants enforced here:
  R-09  sign_skill() writes a 64-byte ed25519 .sig file alongside the .py.
        verify_skill() raises SkillSignatureError if the .sig is absent,
        has wrong length, or fails cryptographic verification.
  R-17  (Phase 1 component) sign_skill() is the mechanism by which validated
        skill files receive their ed25519 signature.  Every .py file that
        reaches SkillRegistry must have a corresponding .sig produced here.
        The evolution/skill_evolver.py (Phase 4) signs skill_versions.json
        entries — that is the second component of R-17.
  R-07  This module never calls exec(), eval(), exec_module(), or any
        importlib execution primitive.  It reads the skill as raw bytes only.
  R-08  sign_skill() must only be called after all three gates have passed.
        It does not perform Gate checks itself — that is schema_gate.py's
        responsibility.

Used by:
  skill_validator/schema_gate.py  — calls sign_skill() after Gate 3 passes
  (verification only: skills/skill_loader.py has its own _verify_skill_signature
   using hash_utils directly, but callers may also call verify_skill() here)

Dependencies:
  utils/hash_utils.py   — ed25519_sign(), ed25519_verify(),
                          ed25519_load_private_key(), ed25519_load_public_key()
  utils/atomic_file.py  — atomic_write_bytes() for crash-safe .sig write
  utils/file_ops.py     — is_safe_filename() for skill name validation
  utils/logger.py       — get_logger()
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Union

from utils.atomic_file import atomic_write_bytes
from utils.file_ops import is_safe_filename
from utils.hash_utils import (
    ed25519_load_private_key,
    ed25519_load_public_key,
    ed25519_sign,
    ed25519_verify,
)
from utils.logger import get_logger

_log = get_logger(__name__, process="orchestrator")

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

#: Expected length of an ed25519 signature in bytes.
_SIG_LENGTH: int = 64

#: File mode for .sig files: owner read/write only (private by design).
_SIG_FILE_MODE: int = 0o600


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------

class SkillSignatureError(RuntimeError):
    """
    Raised when a skill file's ed25519 signature is absent, malformed, or
    cryptographically invalid.

    This exception is a hard security signal.  A caller that receives it
    MUST NOT load or register the skill.  It should log the event at ERROR
    level and reject the skill permanently.

    Attributes:
        skill_path: Path to the .py skill file involved.
        reason:     Short machine-readable reason code.  One of:
                      SIG_FILE_ABSENT    — .sig sibling file does not exist
                      SIG_WRONG_LENGTH   — .sig file is not exactly 64 bytes
                      INVALID_SIGNATURE  — ed25519 verification returned False
                      CRYPTO_ERROR       — ed25519 library raised an exception
                      UNSAFE_SKILL_NAME  — skill filename failed is_safe_filename()
                      KEY_ERROR          — private or public key file is invalid
    """

    def __init__(
        self,
        message: str,
        *,
        skill_path: Union[str, Path, None] = None,
        reason: str = "VERIFICATION_FAILED",
    ) -> None:
        super().__init__(message)
        self.skill_path = Path(skill_path) if skill_path else None
        self.reason = reason

    def __str__(self) -> str:
        base = super().__str__()
        skill_name = self.skill_path.name if self.skill_path else "<unknown>"
        return f"[{self.reason}] {skill_name}: {base}"


