# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

#: On-disk envelope schema version — increment if format changes.
_ENVELOPE_VERSION: int = 1

#: Episode file extension — must match segment_router._EPISODE_EXT.
_EPISODE_EXT: str = ".ep.json"

#: Suffix appended to quarantined episode files during startup scan.
_QUARANTINE_SUFFIX: str = ".quarantine"

#: Expected HMAC key length in bytes (256-bit key).
_HMAC_KEY_LENGTH: int = 32

#: Default subdirectory under data_dir for episodes (used by _DefaultPathResolver).
_EPISODES_SUBDIR: str = "episodes"

#: Namespace directory permissions (owner read/write/execute only).
_NS_DIR_MODE: int = 0o700

#: Episode file permissions (owner read/write only).
_EP_FILE_MODE: int = 0o600


