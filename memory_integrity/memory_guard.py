"""
memory_integrity/memory_guard.py — Phidipus v1.0
HMAC-SHA256 integrity layer — single entry point for all episode read/write.

Architecture contract (R-16 / R-20):
  "All writes: HMAC-SHA256 sign via memory_guard.py.  All reads: verify
   signature, reject invalid.  Startup integrity scan of all core modules
   against SHA256_MANIFEST before the agent loop starts."

MemoryGuard is the ONLY module permitted to read or write episode files
to disk.  No other module in the memory subsystem may perform direct file
I/O.  All callers (EpisodicMemory, VectorMemory) go through this class.

On-disk format (per episode file)
----------------------------------
Each episode is stored as a single JSON file at::

    <episodes_root>/<namespace>/<episode_id>.ep.json

The file contains a signed envelope::

    {
      "data":    { ...episode dict... },
      "hmac":    "<64-char hex HMAC-SHA256>",
      "version": 1
    }

HMAC coverage
-------------
The HMAC-SHA256 is computed over the UTF-8 bytes of the canonical JSON
serialisation of the ``data`` dict (with ``sort_keys=True``).  This
ensures the HMAC is deterministic regardless of key insertion order.

Key management
--------------
The 32-byte HMAC key is loaded from ``cfg.memory.hmac_key_file`` at
construction time.  The key file must be generated by the installer
(``generate_installation_keys()``) with mode 0600 before the daemon
starts.  MemoryGuard validates key length at init and fails fast if the
key is absent or wrong length.

Startup integrity scan (R-20 component)
----------------------------------------
``startup_integrity_scan()`` verifies HMAC signatures on all episodes in
the primary namespace at daemon start.  Episodes that fail verification
are quarantined (renamed to ``<id>.ep.json.quarantine``) and excluded
from normal reads.  The scan result is returned as a dataclass so the
agent loop can decide whether to abort or proceed with warnings.

Namespace routing
-----------------
MemoryGuard accepts an optional ``segment_router`` parameter (a
SegmentRouter instance).  When not provided, an internal
``_DefaultPathResolver`` is used, which provides the same directory
layout without the cross-namespace access control of SegmentRouter.
Production use should always inject a SegmentRouter.

    # Production:
    router = SegmentRouter(cfg)
    guard  = MemoryGuard(cfg, segment_router=router)

    # Phase 1 compat / testing (no access control):
    guard  = MemoryGuard(cfg)

The ``namespace_dir()`` public method is the authorised way for
EpisodicMemory to resolve the index file path, replacing the previous
fragile access to ``guard._router.namespace_dir()``.

Process: orchestrator (L1)

Security invariants enforced here:
  R-16  Every episode written to disk is HMAC-SHA256 signed.
        Every episode read from disk has its HMAC verified before the
        data is returned.  Episodes with invalid or absent HMACs raise
        IntegrityError and are never returned to callers.
  R-20  startup_integrity_scan() verifies all episodes in the primary
        namespace on daemon startup.  Corrupt episodes are quarantined
        and the scan result is reported to the agent loop.
  R-07  No exec(), eval(), exec_module() calls anywhere in this module.
  R-02  No subprocess or OS shell calls.

Used by:
  memory/episodic_memory.py  — write_episode(), read_episode(),
                               delete_episode(), list_episodes(),
                               namespace_dir()

Dependencies:
  memory_integrity/segment_router.py — SegmentRouter (path routing +
                                        namespace access control)
  utils/atomic_file.py               — atomic_write_bytes(), safe_read_bytes()
  utils/hash_utils.py                — hmac_sign(), hmac_verify(), sha256_hex()
  utils/json_utils.py                — dumps(), loads(), dumps_bytes(),
                                       load_bytes(), JsonDecodeError
  utils/file_ops.py                  — safe_join(), ensure_dir(),
                                       is_safe_filename()
  utils/logger.py                    — get_logger()
  config/config_loader.py            — PhidipusConfig
"""

