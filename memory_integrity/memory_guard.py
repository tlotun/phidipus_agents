@dataclass(frozen=True)
class IntegrityScanResult:
    """
    Immutable summary of the startup integrity scan (R-20).

    Attributes:
        namespace:      The namespace that was scanned.
        total:          Total number of episode files found.
        verified:       Episodes that passed HMAC verification.
        quarantined:    Episodes that failed and were quarantined.
        skipped:        Episodes skipped due to unreadable files.
        quarantine_ids: IDs of episodes that were quarantined.
    """

    namespace:      str
    total:          int
    verified:       int
    quarantined:    int
    skipped:        int
    quarantine_ids: tuple[str, ...] = field(default_factory=tuple)

    @property
    def all_ok(self) -> bool:
        """True iff no episodes were quarantined or skipped."""
        return self.quarantined == 0 and self.skipped == 0


# ---------------------------------------------------------------------------
# Internal fallback path resolver (no access control)
# ---------------------------------------------------------------------------

class _DefaultPathResolver:
    """
    Minimal path resolver used when no SegmentRouter is injected.

    Provides the same directory layout as SegmentRouter but does NOT
    enforce cross-namespace read access control.  For production use,
    always inject a SegmentRouter.
    """

    def __init__(self, data_dir: Path) -> None:
        self._episodes_root = data_dir / _EPISODES_SUBDIR
        for ns in sorted(VALID_NAMESPACES):
            ensure_dir(self._episodes_root / ns, mode=_NS_DIR_MODE)

    def resolve_path(self, namespace: str, episode_id: str) -> Path:
        if namespace not in VALID_NAMESPACES:
            raise NamespaceError(
                f"Unknown namespace {namespace!r}.",
                namespace=namespace,
            )
        ns_dir = ensure_dir(self._episodes_root / namespace, mode=_NS_DIR_MODE)
        return safe_join(ns_dir, episode_id + _EPISODE_EXT)

    def namespace_dir(self, namespace: str) -> Path:
        if namespace not in VALID_NAMESPACES:
            raise NamespaceError(
                f"Unknown namespace {namespace!r}.",
                namespace=namespace,
            )
        return ensure_dir(self._episodes_root / namespace, mode=_NS_DIR_MODE)


