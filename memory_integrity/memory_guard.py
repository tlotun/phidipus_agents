class MemoryGuard:
    """
    HMAC-SHA256 integrity layer — sole gatekeeper for episode persistence.

    All episode reads and writes in the Phidipus memory subsystem must go
    through this class.  No other module is permitted to touch episode
    files on disk directly.

    Usage::

        # Production (with namespace access control):
        router = SegmentRouter(cfg)
        guard  = MemoryGuard(cfg, segment_router=router)

        # Write a signed episode:
        dest = guard.write_episode(
            {"id": "ep-001", "task": "open browser", "outcome": "success"},
            namespace="primary",
        )

        # Read and verify:
        episode = guard.read_episode("ep-001", namespace="primary")

        # Startup scan (R-20):
        result = guard.startup_integrity_scan(namespace="primary")
        if not result.all_ok:
            logger.error("Integrity scan found corrupt episodes", ...)

    Args:
        cfg:            Validated PhidipusConfig.
        segment_router: Optional SegmentRouter for namespace access control.
                        If None, a _DefaultPathResolver is used (no
                        cross-namespace access enforcement).
    """

    def __init__(
        self,
        cfg:            PhidipusConfig,
        segment_router: SegmentRouter | None = None,
    ) -> None:
        # ── HMAC key ────────────────────────────────────────────────────
        hmac_key_path = Path(cfg.memory.hmac_key_file)
        if not hmac_key_path.exists():
            raise MemoryGuardError(
                f"HMAC key file not found: {hmac_key_path}. "
                "Run the installer to generate keys before starting.",
                reason="KEY_NOT_FOUND",
            )
        self._hmac_key: bytes = hmac_key_path.read_bytes()
        if len(self._hmac_key) != _HMAC_KEY_LENGTH:
            raise MemoryGuardError(
                f"HMAC key at {hmac_key_path} is {len(self._hmac_key)} bytes; "
                f"expected exactly {_HMAC_KEY_LENGTH} bytes. "
                "The key file may be corrupt — re-run the installer.",
                reason="KEY_INVALID",
            )

        # ── Path router ──────────────────────────────────────────────────
        if segment_router is not None:
            self._router: SegmentRouter | _DefaultPathResolver = segment_router
        else:
            self._router = _DefaultPathResolver(Path(cfg.paths.data_dir))
            _log.warning(
                "MemoryGuard: no SegmentRouter injected — "
                "cross-namespace access control is DISABLED. "
                "Use SegmentRouter in production.",
            )

        _log.info(
            "MemoryGuard initialised",
            extra={
                "hmac_key_path":    str(hmac_key_path),
                "segment_router":   segment_router is not None,
                "default_namespace": cfg.memory.episode_namespace,
            },
        )

    # ------------------------------------------------------------------
    # Public protocol: namespace_dir()
    # ------------------------------------------------------------------

    def namespace_dir(self, namespace: str) -> Path:
        """
        Return the resolved directory Path for *namespace*.

        This is the authorised replacement for accessing ``guard._router``
        directly (which EpisodicMemory previously used to resolve its
        index file path).  Callers should use this method instead of
        touching the internal ``_router`` attribute.

        Args:
            namespace: One of "primary", "guest", "untrusted".

        Returns:
            Absolute Path to the namespace directory (created if needed).

        Raises:
            NamespaceError: if *namespace* is not valid.
        """
        return self._router.namespace_dir(namespace)

    # ------------------------------------------------------------------
    # Public write / read / delete / list
    # ------------------------------------------------------------------

    def write_episode(
        self,
        episode:   dict[str, Any],
        namespace: str = "primary",
    ) -> Path:
        """
        Validate, sign, and write *episode* to disk (R-16).

        Signing process:
          1. Validate episode has a non-empty ``"id"`` field.
          2. Validate ``episode["id"]`` is a safe filename component.
          3. Serialise ``episode`` with ``sort_keys=True`` for deterministic HMAC.
          4. Compute HMAC-SHA256 over the serialised bytes.
          5. Wrap in a signed envelope: ``{"data": ..., "hmac": ..., "version": 1}``.
          6. Write envelope atomically with mode 0o600.

        Args:
            episode:   Episode dict.  Must contain a non-empty ``"id"`` key.
                       All values must be JSON-serialisable.
            namespace: Target namespace ("primary", "guest", "untrusted").

        Returns:
            Path to the written episode file.

        Raises:
            EpisodeValidationError: if episode structure is invalid.
            NamespaceError:         if namespace is not valid.
            MemoryGuardError:       on I/O failure.
        """
        # ── Validate episode structure ───────────────────────────────────
        if not isinstance(episode, dict):
            raise EpisodeValidationError(
                f"Episode must be a dict, got {type(episode).__name__!r}.",
                field="<root>",
                reason="INVALID_TYPE",
            )
        episode_id: str = episode.get("id", "")  # type: ignore[assignment]
        if not isinstance(episode_id, str) or not episode_id:
            raise EpisodeValidationError(
                "Episode must have a non-empty string 'id' field.",
                field="id",
                reason="MISSING_ID",
            )
        # Validate the ID is safe to use as a filename component.
        # is_safe_filename checks for path traversal characters.
        if not is_safe_filename(episode_id):
            raise EpisodeValidationError(
                f"Episode id {episode_id!r} contains unsafe characters. "
                "Only alphanumerics, underscores, hyphens, and dots are allowed.",
                field="id",
                reason="UNSAFE_ID",
            )

        # ── Build HMAC ───────────────────────────────────────────────────
        try:
            data_bytes: bytes = dumps(episode, sort_keys=True).encode("utf-8")
        except (ValueError, TypeError) as exc:
            raise EpisodeValidationError(
                f"Episode is not JSON-serialisable: {exc}",
                field="<root>",
                reason="NOT_SERIALISABLE",
            ) from exc

        mac: bytes    = hmac_sign(self._hmac_key, data_bytes)
        mac_hex: str  = mac.hex()

        # ── Build envelope ───────────────────────────────────────────────
        envelope: dict[str, Any] = {
            "version": _ENVELOPE_VERSION,
            "data":    episode,
            "hmac":    mac_hex,
        }

        # ── Resolve path and write ───────────────────────────────────────
        dest: Path = self._router.resolve_path(namespace, episode_id)

        try:
            envelope_bytes = dumps(envelope, sort_keys=True).encode("utf-8")
            atomic_write_bytes(dest, envelope_bytes, mode=_EP_FILE_MODE)
        except Exception as exc:
            raise MemoryGuardError(
                f"Failed to write episode {episode_id!r} to {dest}: {exc}",
                reason="WRITE_FAILED",
            ) from exc

        _log.debug(
            "R-16: episode written and signed",
            extra={
                "episode_id": episode_id,
                "namespace":  namespace,
                "dest":       str(dest),
            },
        )
        return dest

    def read_episode(
        self,
        episode_id: str,
        namespace:  str = "primary",
        *,
        caller_ns:  str = "",
    ) -> dict[str, Any]:
        """
        Read and HMAC-verify an episode from disk (R-16).

        Verification process:
          1. Enforce namespace read isolation if caller_ns is provided and
             the router is a SegmentRouter (Bug #14 fix).
          2. Resolve the episode file path via the router.
          3. Read the raw bytes from disk.
          4. Parse the JSON envelope.
          5. Re-serialise ``envelope["data"]`` with ``sort_keys=True``.
          6. Verify HMAC-SHA256 against the stored ``envelope["hmac"]``.
          7. Return ``envelope["data"]`` only if HMAC is valid.

        Args:
            episode_id: Episode identifier.
            namespace:  Source namespace.
            caller_ns:  The namespace the calling agent is operating in.
                        When provided and the router is a SegmentRouter,
                        cross-namespace access control is enforced (R-16).
                        When empty (default), no access control check is
                        performed — for backward compatibility with callers
                        that do not yet pass caller_ns.

        Returns:
            Verified episode dict.

        Raises:
            EpisodeNotFoundError:  if the episode file does not exist.
            IntegrityError:        if HMAC verification fails (R-16).
            NamespaceAccessError:  if caller_ns is not permitted to read
                                   namespace (R-16, Bug #14 fix).
            MemoryGuardError:      on I/O or parse error.
        """
        # Bug #14 fix: enforce namespace read isolation when caller_ns is
        # provided and the router supports access control.
        if caller_ns and isinstance(self._router, SegmentRouter):
            self._router.check_read_allowed(caller_ns, namespace)

        path: Path = self._router.resolve_path(namespace, episode_id)

        if not path.exists():
            raise EpisodeNotFoundError(
                f"Episode {episode_id!r} not found in namespace {namespace!r}.",
                episode_id=episode_id,
                namespace=namespace,
            )

        # ── Read and parse ───────────────────────────────────────────────
        try:
            raw: bytes = path.read_bytes()
            envelope   = loads(raw.decode("utf-8"))
        except (OSError, UnicodeDecodeError, JsonDecodeError) as exc:
            raise MemoryGuardError(
                f"Cannot read episode {episode_id!r}: {exc}",
                reason="READ_FAILED",
            ) from exc

        if not isinstance(envelope, dict):
            raise IntegrityError(
                f"Episode {episode_id!r} envelope is not a JSON object.",
                episode_id=episode_id,
                reason="ENVELOPE_CORRUPT",
            )

        # ── Extract fields ───────────────────────────────────────────────
        stored_mac_hex: str = envelope.get("hmac", "")
        data: Any           = envelope.get("data")

        if not stored_mac_hex or not isinstance(stored_mac_hex, str):
            raise IntegrityError(
                f"Episode {episode_id!r} has missing or invalid 'hmac' field (R-16).",
                episode_id=episode_id,
                reason="HMAC_MISSING",
            )
        if not isinstance(data, dict):
            raise IntegrityError(
                f"Episode {episode_id!r} 'data' field is not a dict.",
                episode_id=episode_id,
                reason="DATA_CORRUPT",
            )

        # ── Verify HMAC ──────────────────────────────────────────────────
        # Re-serialise data with sort_keys=True to produce the same bytes
        # that were signed during write_episode().
        try:
            data_bytes: bytes = dumps(data, sort_keys=True).encode("utf-8")
            stored_mac: bytes = bytes.fromhex(stored_mac_hex)
        except (ValueError, TypeError) as exc:
            raise IntegrityError(
                f"Episode {episode_id!r} HMAC field is malformed: {exc}",
                episode_id=episode_id,
                reason="HMAC_MALFORMED",
            ) from exc

        if not hmac_verify(self._hmac_key, data_bytes, stored_mac):
            _log.error(
                "R-16 VIOLATION: episode HMAC verification FAILED",
                extra={
                    "episode_id": episode_id,
                    "namespace":  namespace,
                    "path":       str(path),
                    "reason":     "HMAC_INVALID",
                },
            )
            raise IntegrityError(
                f"Episode {episode_id!r} HMAC is invalid (R-16). "
                "The episode file may have been tampered with or the "
                "HMAC key has changed.",
                episode_id=episode_id,
                reason="HMAC_INVALID",
            )

        _log.debug(
            "R-16: episode verified and returned",
            extra={"episode_id": episode_id, "namespace": namespace},
        )
        return data

    def delete_episode(
        self,
        episode_id: str,
        namespace:  str = "primary",
    ) -> bool:
        """
        Delete an episode file from disk.

        Args:
            episode_id: Episode identifier.
            namespace:  Namespace to delete from.

        Returns:
            True if the file was deleted, False if it did not exist.

        Raises:
            MemoryGuardError: on I/O failure other than FileNotFoundError.
        """
        path: Path = self._router.resolve_path(namespace, episode_id)

        if not path.exists():
            return False

        try:
            path.unlink()
        except OSError as exc:
            raise MemoryGuardError(
                f"Failed to delete episode {episode_id!r}: {exc}",
                reason="DELETE_FAILED",
            ) from exc

        _log.debug(
            "MemoryGuard: episode deleted",
            extra={"episode_id": episode_id, "namespace": namespace},
        )
        return True

    def list_episodes(self, namespace: str = "primary") -> list[str]:
        """
        List all episode IDs present on disk in *namespace*.

        Returns IDs sorted alphabetically (insertion order is maintained
        by EpisodicMemory's index; this method is for count/existence checks).

        Args:
            namespace: Namespace to list.

        Returns:
            Sorted list of episode IDs (without the ``.ep.json`` extension).

        Raises:
            NamespaceError: if namespace is not valid.
        """
        ns_dir: Path = self._router.namespace_dir(namespace)
        ids: list[str] = []
        try:
            for p in ns_dir.iterdir():
                # Bug #12 fix: also reject filenames that contain the
                # quarantine marker anywhere (e.g. "evil.ep.json.quarantine.ep.json"
                # would pass the old suffix-only check).
                if (p.name.endswith(_EPISODE_EXT)
                        and _QUARANTINE_SUFFIX not in p.name):
                    ep_id = p.name[: -len(_EPISODE_EXT)]
                    ids.append(ep_id)
        except OSError as exc:
            _log.warning(
                "MemoryGuard: could not list episodes",
                extra={"namespace": namespace, "error": str(exc)},
            )
        return sorted(ids)

    # ------------------------------------------------------------------
    # Startup integrity scan (R-20)
    # ------------------------------------------------------------------

    def startup_integrity_scan(
        self,
        namespace: str = "primary",
    ) -> IntegrityScanResult:
        """
        Verify HMAC signatures on all episodes in *namespace* (R-20).

        Episodes that fail verification are quarantined by renaming them
        to ``<id>.ep.json.quarantine``.  They are excluded from normal
        reads and from ``list_episodes()``.

        This method is called once at agent-loop startup.  The result is
        returned to the caller (agent_loop.py) which decides whether to
        abort or proceed with a warning if any episodes were quarantined.

        Args:
            namespace: Namespace to scan (default: "primary").

        Returns:
            IntegrityScanResult with counts and quarantined IDs.
        """
        ns_dir: Path = self._router.namespace_dir(namespace)

        total       = 0
        verified    = 0
        quarantined = 0
        skipped     = 0
        quarantine_ids: list[str] = []

        try:
            ep_paths = [
                p for p in ns_dir.iterdir()
                if p.name.endswith(_EPISODE_EXT)
                and not p.name.endswith(_QUARANTINE_SUFFIX)
            ]
        except OSError as exc:
            _log.error(
                "R-20: startup integrity scan could not list namespace directory",
                extra={"namespace": namespace, "error": str(exc)},
            )
            return IntegrityScanResult(
                namespace=namespace,
                total=0, verified=0, quarantined=0, skipped=1,
            )

        for ep_path in ep_paths:
            total += 1
            ep_id = ep_path.name[: -len(_EPISODE_EXT)]

            try:
                self.read_episode(ep_id, namespace=namespace)
                verified += 1
            except IntegrityError as exc:
                # Quarantine the corrupt file
                quarantine_path = ep_path.with_suffix(
                    _EPISODE_EXT + _QUARANTINE_SUFFIX
                )
                try:
                    ep_path.rename(quarantine_path)
                    quarantine_ids.append(ep_id)
                    quarantined += 1
                    _log.error(
                        "R-20: episode quarantined — HMAC invalid",
                        extra={
                            "episode_id":      ep_id,
                            "namespace":       namespace,
                            "quarantine_path": str(quarantine_path),
                            "reason":          exc.reason,
                        },
                    )
                except OSError as rename_exc:
                    skipped += 1
                    _log.error(
                        "R-20: could not quarantine corrupt episode",
                        extra={
                            "episode_id": ep_id,
                            "error":      str(rename_exc),
                        },
                    )
            except (MemoryGuardError, EpisodeNotFoundError) as exc:
                skipped += 1
                _log.warning(
                    "R-20: skipping unreadable episode during scan",
                    extra={"episode_id": ep_id, "error": str(exc)},
                )

        result = IntegrityScanResult(
            namespace=namespace,
            total=total,
            verified=verified,
            quarantined=quarantined,
            skipped=skipped,
            quarantine_ids=tuple(quarantine_ids),
        )

        log_fn = _log.info if result.all_ok else _log.error
        log_fn(
            "R-20: startup integrity scan complete",
            extra={
                "namespace":   namespace,
                "total":       total,
                "verified":    verified,
                "quarantined": quarantined,
                "skipped":     skipped,
                "all_ok":      result.all_ok,
            },
        )
        return result

    def scan_integrity(self, namespace: str = "primary") -> "IntegrityScanAdapter":
        """
        M-16 FIX: Public scan_integrity() wrapper called by agent_loop.startup().
        Runs startup_integrity_scan() and returns a unified adapter
        with fields expected by agent_loop (all_valid, invalid_hmac, etc.).
        Now returns meaningful results — not always-warning.
        """
        result = self.startup_integrity_scan(namespace=namespace)

        class IntegrityScanAdapter:
            def __init__(self, r: "IntegrityScanResult") -> None:
                self.all_valid: bool    = r.all_ok
                self.invalid_hmac: int  = r.quarantined
                self.unreadable: int    = r.skipped
                self.total_files: int   = r.total
                self.invalid_ids: list  = list(r.quarantine_ids)

        return IntegrityScanAdapter(result)
