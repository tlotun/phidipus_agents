class IntegrityError(RuntimeError):
    """
    Raised when an episode's HMAC-SHA256 signature fails verification (R-16).

    A caller that receives this exception MUST NOT use the episode data.
    The episode file should be quarantined or deleted.

    Attributes:
        episode_id: The episode identifier that failed verification.
        reason:     Short machine-readable reason code.
    """

    def __init__(
        self,
        message:    str,
        *,
        episode_id: str = "",
        reason:     str = "HMAC_INVALID",
    ) -> None:
        super().__init__(message)
        self.episode_id = episode_id
        self.reason     = reason

    def __str__(self) -> str:
        parts = [f"[{self.reason}]"]
        if self.episode_id:
            parts.append(f"id={self.episode_id!r}")
        return " ".join(parts) + f" {super().__str__()}"


class EpisodeNotFoundError(FileNotFoundError):
    """
    Raised when an episode file does not exist on disk.

    Attributes:
        episode_id: The missing episode identifier.
        namespace:  The namespace that was searched.
        reason:     Always "EPISODE_NOT_FOUND".
    """

    def __init__(
        self,
        message:    str,
        *,
        episode_id: str = "",
        namespace:  str = "",
        reason:     str = "EPISODE_NOT_FOUND",
    ) -> None:
        super().__init__(message)
        self.episode_id = episode_id
        self.namespace  = namespace
        self.reason     = reason

    def __str__(self) -> str:
        parts = [f"[{self.reason}]"]
        if self.episode_id:
            parts.append(f"id={self.episode_id!r}")
        if self.namespace:
            parts.append(f"ns={self.namespace!r}")
        return " ".join(parts) + f" {super().__str__()}"


class EpisodeValidationError(ValueError):
    """
    Raised when an episode dict fails structural validation before write.

    Attributes:
        field:  Dot-path to the offending field (e.g. ``"id"``).
        reason: Short machine-readable reason code.
    """

    def __init__(
        self,
        message: str,
        *,
        field:  str = "",
        reason: str = "VALIDATION_ERROR",
    ) -> None:
        super().__init__(message)
        self.field  = field
        self.reason = reason

    def __str__(self) -> str:
        parts = [f"[{self.reason}]"]
        if self.field:
            parts.append(f"field={self.field!r}")
        return " ".join(parts) + f" {super().__str__()}"


class MemoryGuardError(RuntimeError):
    """
    Raised on MemoryGuard operational errors (key loading, I/O failures).

    Attributes:
        reason: Short machine-readable reason code.
    """

    def __init__(self, message: str, *, reason: str = "GUARD_ERROR") -> None:
        super().__init__(message)
        self.reason = reason

    def __str__(self) -> str:
        return f"[{self.reason}] {super().__str__()}"


