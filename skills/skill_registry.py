"""
skills/skill_registry.py — Phidipus v1.20 (FIX #2)
Registry for validated, signed skill definitions with quarantine + human-approval gate.

Architecture contract (R-08 / R-09):
  "Register only validated, signed skills.  Add quarantine status for
   new skills.  No loading unsigned skill."

FIX #2 — Human-approval gate:
  ALL LLM-generated and evolved skills now require explicit admin approval
  before they can execute.  The approval gate sits BEFORE the quarantine gate:

      Generated/Evolved skill
          ↓
      Gate 1-2-3 (AST + Docker + Schema)  ← existing
          ↓
      pending_human_approval = True        ← FIX #2: NEW gate
          ↓  (admin approves via Admin Panel or Telegram)
      quarantined = True                   ← existing
          ↓  (runs successfully once)
      quarantined = False  →  active

  Rationale: Gate 1-3 validate syntax and schema, but cannot fully prevent
  a malicious skill that passes all static checks from being executed on the
  host.  A human admin reviewing the skill code before approval is the only
  defence against a Gate-bypass.  The review is a one-time action per skill.

  Manually written / builtin skills are pre-approved (pending=False) because
  they are written by the developer, not generated by an LLM.

SkillRegistry maintains an in-memory catalogue of validated skills and
persists it to skill_versions.json (signed with ed25519 after every
write, R-17).  Only skills that have passed the 3-gate validator and
carry a valid .sig file can be registered (R-09).

Quarantine
----------
Every newly registered skill starts in quarantine.  A quarantined skill
can be discovered and loaded, but the agent loop treats it as untrusted
and may require human confirmation before executing it.  A skill exits
quarantine after executing successfully at least once (promote()).

Process: orchestrator (L1)

Security invariants enforced here:
  R-08  register() rejects skills that lack a ValidationResult.
  R-09  register() verifies the .sig file exists and is valid before
        adding the skill to the registry.
  R-17  Every write to skill_versions.json is immediately followed by
        sign_skill_versions().  On load, the signature is VERIFIED before
        trusting the file contents — tampered registries are rejected.
  FIX-2 approve() is the ONLY path to clear pending_human_approval.
        is_executable() blocks execution until both pending_human_approval=False
        AND quarantined=False (or quarantine override is explicitly requested).

Used by:
  core/agent_loop.py            — register_skill(), get_skill(), is_executable()
  evolution/skill_evolver.py    — register after evolution
  admin/admin_server_v2.py      — approve_skill() endpoint
  telegram/telegram_bot.py      — /skills approve <name>

Dependencies:
  skills/base_skill.py              — BaseSkillDefinition
  skill_validator/schema_gate.py    — ValidationResult
  skill_validator/skill_signer.py   — verify_skill()
  evolution/skill_version_signer.py — sign_skill_versions(),
                                       verify_skill_versions()
  utils/atomic_file.py              — atomic_write_text(), safe_read_bytes()
  utils/json_utils.py               — dumps(), loads()
  utils/logger.py                   — get_logger()
  config/config_loader.py           — PhidipusConfig

FIX (BUG-3 / R-17): _load_versions() previously loaded skill_versions.json
  WITHOUT verifying the ed25519 signature.  An attacker who tampered with
  skill_versions.json could inject unvalidated skills into the registry.
  Fixed by calling verify_skill_versions() before parsing the file.
  If verification fails, the file is rejected and the registry starts empty.
"""

